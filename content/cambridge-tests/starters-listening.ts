const CAST = { W: "en-GB-LibbyNeural", G: "en-GB-MaisieNeural" };
const COLOURS = ["red", "blue", "green", "yellow", "orange", "purple", "pink", "brown", "grey", "black"];
const GAP = 3; // seconds of silence after each question, as in the exam

const audio = (n: number, part: number) => `/audio/cambridge/starters-${n}/part-${part}.mp3`;
const intro = (text: string): Line => ({ who: "N", text, pause: 1.5 });
/** A two-line exchange; the answer line is followed by time to write. */
const ex = (w: string, g: string, wFirst = true): Line[] =>
  wFirst ? [{ who: "W", text: w }, { who: "G", text: g, pause: GAP }] : [{ who: "G", text: g }, { who: "W", text: w, pause: GAP }];
const q = (n: string, text: string): Line => ({ who: "N", text: `${n}. ${text}`, pause: 0.6 });

